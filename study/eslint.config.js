'use strict';

// =============================================================================
// КОНФИГУРАЦИЯ ESLint (SAST-инструмент)
// -----------------------------------------------------------------------------
// SAST (Static Application Security Testing) — статический анализ кода:
// инструмент ИЩЕТ опасные паттерны в исходниках БЕЗ запуска программы.
//
// Здесь мы используем ESLint + плагин eslint-plugin-security, который
// подсвечивает типичные уязвимости:
//   - eval() / конструктор Function / new Function (выполнение произвольного кода);
//   - «небезопасные» регулярные выражения (ReDoS);
//   - небезопасный доступ к свойствам объекта (object injection);
//   - сравнение секретов «в лоб» (timing attacks) и т.д.
//
// В CI этот конфиг запускается командой `npx eslint .`
// (см. .github/workflows/ci.yml — шаг «SAST»).
// =============================================================================

const security = require('eslint-plugin-security'); // сам плагин

// module.exports — МАССИВ конфигов (flat config, формат ESLint 9+/10+).
module.exports = [
  {
    // Какие пути НЕ анализировать:
    ignores: ['node_modules/**', 'data/**', 'coverage/**'],
  },
  // Готовый набор правил «рекомендуемые» от eslint-plugin-security —
  // включает все detection-правила плагина.
  security.configs.recommended,
  {
    // Применяем правила ко всем .js-файлам проекта.
    files: ['**/*.js'],
    languageOptions: {
      ecmaVersion: 2022,       // синтаксис ECMAScript 2022
      sourceType: 'commonjs',  // проект на CommonJS (require/module.exports)
      globals: {
        // Явно объявляем глобальные переменные среды выполнения, иначе
        // правило no-undef будет считать их ошибками:
        console: 'readonly',        // из Node.js
        process: 'readonly',        // из Node.js
        Buffer: 'readonly',         // из Node.js
        URL: 'readonly',            // встроенный класс URL
        setTimeout: 'readonly',     // таймеры
        fetch: 'readonly',          // глобальный fetch в Node 18+ (используется в тестах)
        AbortController: 'readonly',// встроенный класс (fetch/таймауты)
      },
    },
    rules: {
      // Стандартные проверки качества:
      'no-unused-vars': ['error', { argsIgnorePattern: '^_' }],
      //   ^ неиспользуемые переменные — ошибка; аргументы, начинающиеся с '_'
      //     (например, next в обработчике ошибок) игнорируются
      'no-undef': 'error', // использование необъявленной переменной — ошибка

      // Отключаем ДВА правила плагина — это СОЗНАТЕЛЬНЫЕ исключения
      // (иначе были бы ложные срабатывания):

      // 1) detect-possible-timing-attacks ругается на прямое сравнение строк
      //    (например, scheme !== 'Bearer'). У нас пароли сравниваются только
      //    через bcrypt.compareSync, а токены — через jwt.verify: обе функции
      //    реализуют устойчивое к timing-атакам сравнение внутри себя.
      'security/detect-possible-timing-attacks': 'off',

      // 2) detect-non-literal-fs-filename ругается на путь к БД из переменной
      //    окружения (fs.mkdirSync(path.dirname(config.dbPath))). Это не
      //    пользовательский ввод — путь задаёт администратор через env.
      'security/detect-non-literal-fs-filename': 'off',
    },
  },
];

// =============================================================================
// ЗАЧЕМ ЭТО В ПРОЕКТЕ:
// - статический анализ ловит классы ошибок ДО того, как код попадёт в прод;
// - в CI он работает автоматически на каждый push/PR — человек не забудет;
// - впрочем, SAST не заменяет тесты (динамический анализ): поэтому в CI
//   есть и те (npm test), и SCA (npm audit).
// =============================================================================