'use strict';

// =============================================================================
// СБОРКА EXPRESS-ПРИЛОЖЕНИЯ
// -----------------------------------------------------------------------------
// Этот модуль «склеивает» всё приложение: подключает middleware (промежуточные
// обработчики), публичные и защищённые маршруты, обработчики ошибок.
//
// Важно понимать ПОРЯДОК middleware: Express выполняет их строго в том
// порядке, в котором они зарегистрированы (app.use / app.get / ...).
// Поэтому сначала ставятся глобальные защиты, потом маршруты.
// =============================================================================

const express = require('express');
const helmet = require('helmet');                 // набор защитных HTTP-заголовков
const { createAuth } = require('./auth');          // JWT-подпись и проверка
const { authRoutes } = require('./routes/authRoutes'); // POST /auth/login
const dataRoutes = require('./routes/dataRoutes');     // GET /api/data, POST /api/posts

/**
 * createApp({ db, config }) — фабрика Express-приложения.
 * Аргументы: готовые база данных (db) и конфигурация (config).
 * Это позволяет тестам создать своё приложение с базой в памяти.
 */
function createApp({ db, config }) {
  const app = express();
  const auth = createAuth(config); // аутентификация с нашим JWT-секретом

  // app.locals — общее хранилище данных приложения. Маршруты обращаются к нему
  // через req.app.locals (например, req.app.locals.db). Так роуты получают
  // доступ к БД и функциям подписи токенов, не импортируя их напрямую.
  app.locals.db = db;
  app.locals.config = config;
  app.locals.auth = auth;

  // --- ГЛОБАЛЬНЫЕ ЗАЩИТЫ (выполняются для КАЖДОГО запроса) -------------------

  // Убираем заголовок X-Powered-By: Express. Он сообщал бы атакующему
  // технологию сервера (а значит, и список известных уязвимостей).
  app.disable('x-powered-by');

  // helmet() — добавляет защитные HTTP-заголовки ответа:
  // Content-Security-Policy, X-Content-Type-Options (запрет MIME-sniffing),
  // Strict-Transport-Security (HSTS), X-Frame-Options и др. — OWASP A05.
  app.use(helmet());

  // express.json() — разбор тела запроса (JSON). limit '10kb' жёстко
  // ограничивает размер тела: защита от DoS-атак гигантскими запросами.
  app.use(express.json({ limit: '10kb' }));

  // --- ПУБЛИЧНЫЕ ЭНДПОИНТЫ ----------------------------------------------------

  // GET /health — проверка живости сервиса (используется в CI/CD и мониторинге).
  app.get('/health', (req, res) => res.json({ status: 'ok' }));

  // Все маршруты /auth/* (сейчас это POST /auth/login) — ПУБЛИЧНЫЕ:
  // аутентификация не должна требовать токена, наоборот, здесь его выдают.
  app.use('/auth', authRoutes({ config }));

  // --- ЗАЩИЩЁННАЯ ЗОНА -------------------------------------------------------

  // Всё, что смонтировано под /api/*, ПРОХОДИТ через middleware
  // auth.authenticateToken: без валидного JWT — ответ 401, маршрут не вызовется.
  app.use('/api', auth.authenticateToken, dataRoutes);

  // --- ОБРАБОТКА ОШИБОК ------------------------------------------------------

  // 404: если ни один маршрут не совпал — JSON-ответ «Not found»
  // (а не HTML-страница Express, чтобы не раскрывать лишнего).
  app.use((req, res) => res.status(404).json({ error: 'Not found' }));

  // Централизованный обработчик ошибок. Express вызывает его, когда в любом
  // middleware/обработчике произошла ошибка (передана в next(err)).
  // Особенность: сигнатура из ЧЕТЫРЁХ аргументов (err, req, res, next) —
  // по ней Express понимает, что это обработчик ошибок.
  // eslint-disable-next-line no-unused-vars
  app.use((err, req, res, next) => {
    console.error('[error]', err.message);          // пишем подробности В ЛОГ
    // Клиенту отдаём ТОЛЬКО общее сообщение — стектрейсы и детали не утекают.
    res.status(err.status || 500).json({ error: 'Internal server error' });
  });

  return app; // готовое приложение
}

module.exports = { createApp };

// =============================================================================
// ИТОГ:
// - глобальные защиты (helmet, лимит тела, без x-powered-by);
// - чёткое разделение: /auth — публично, /api — только с JWT;
// - 404 и ошибки отвечают JSON без утечки внутренностей (OWASP A05).
// =============================================================================