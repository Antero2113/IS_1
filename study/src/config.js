'use strict';

// =============================================================================
// КОНФИГУРАЦИЯ ПРИЛОЖЕНИЯ
// -----------------------------------------------------------------------------
// Централизованное место, где приложение читает свои настройки.
// Настройки берутся из ПЕРЕМЕННЫХ ОКРУЖЕНИЯ (process.env), а не «зашиты» в код.
// Это важно по двум причинам:
//   1) секреты (JWT_SECRET) нельзя коммитить в git — их задают через env;
//   2) одно и то же приложение можно запускать с разными настройками
//      (локально, в тестах, в CI, на проде) без изменения кода.
// =============================================================================

// Значение JWT-секрета «по умолчанию» — ТОЛЬКО для локальной разработки.
// Используется, если переменная окружения JWT_SECRET не задана.
const DEFAULT_JWT_SECRET = 'insecure-dev-secret-change-me';

/**
 * getConfig(env) — собирает объект настроек.
 * Аргумент `env` по умолчанию равен process.env (переменные окружения),
 * но в тестах туда можно передать произвольный объект.
 */
function getConfig(env = process.env) {
  // Берём секрет из окружения или подставляем dev-значение.
  const jwtSecret = env.JWT_SECRET || DEFAULT_JWT_SECRET;

  // Предупреждение в консоль, если секрет слабый/не задан:
  // если кто-то узнает JWT-секрет, он сможет подделывать токены и
  // выдавать себя за любого пользователя — поэтому молчать об этом нельзя.
  if (jwtSecret === DEFAULT_JWT_SECRET || jwtSecret.length < 16) {
    console.warn(
      '[config] WARNING: JWT_SECRET is missing/weak. Set a strong secret (>=16 chars).'
    );
  }

  // Возвращаем объект со всеми настройками.
  return {
    port: Number(env.PORT) || 3000,                    // порт HTTP-сервера
    dbPath: env.DB_PATH || './data/app.db',            // путь к файлу SQLite
    jwtSecret,                                         // секрет подписи JWT
    jwtExpiresIn: env.JWT_EXPIRES_IN || '1h',          // время жизни токена ('1h', '15m', ...)

    // Защита от брутфорса на /auth/login:
    loginRateLimitWindowMs: Number(env.LOGIN_RATE_LIMIT_WINDOW_MS) || 15 * 60 * 1000,
    //   ^ окно времени (по умолчанию 15 минут = 15*60*1000 мс)
    loginRateLimitMax: Number(env.LOGIN_RATE_LIMIT_MAX) || 5,
    //   ^ максимум попыток входа с одного IP за это окно
  };
}

// Экспортируем функцию, чтобы её могли использовать server.js и тесты.
module.exports = { getConfig };

// =============================================================================
// ПОЧЕМУ ЭТО БЕЗОПАСНО:
// - Пароли и секреты никогда не попадают в исходный код и не утекают в git
//   (.env* добавлен в .gitignore).
// - Слабый/дефолтный секрет заметно предупреждает разработчика при старте.
// =============================================================================