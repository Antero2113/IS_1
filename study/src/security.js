// =============================================================================
// САНИТИЗАЦИЯ ВВОДА И ЭКРАНИРОВАНИЕ ВЫВОДА
// -----------------------------------------------------------------------------
// Здесь собраны вспомогательные функции защиты от двух классов атак:
//   1) XSS (Cross-Site Scripting) — злоумышленник пытается «внедрить» HTML/JS
//      в данные, которые потом отдаёт API. Если эти данные отрендерить как
//      HTML, скрипт выполнится в браузере жертвы. Лечится ЭКРАНИРОВАНИЕМ:
//      спецсимволы (<, >, ", ', &, /) превращаются в безопасные сущности.
//   2) «Грязный» ввод — лишние пробелы, управляющие символы. Лечится
//      САНИТИЗАЦИЕЙ (чистка) + ВАЛИДАЦИЕЙ (проверка формата и длины).
// Ссылка: OWASP XSS Prevention Cheat Sheet.
// =============================================================================

/**
 * escapeHtml(input) — OWASP-рекомендуемое экранирование HTML-сущностей.
 * Применяется ко ВСЕМ пользовательским данным ПЕРЕД тем, как они попадут
 * в ответ API (защита от stored/reflected XSS).
 *
 * Как это работает: регулярное выражение /[&<>"'/]/g находит каждый опасный
 * символ, а switch заменяет его на безопасную HTML-сущность.
 * Например '<script>' превратится в '<script>' — браузер покажет это
 * как текст, но НЕ выполнит как код.
 *
 * Сущности собраны конкатенацией строк ('&' + 'amp;'), чтобы никакие
 * инструменты не «съели» их как настоящие HTML-сущности. switch получает
 * только символы из фиксированного списка [&<>"'/], поэтому это безопасно.
 */
function escapeHtml(input) {
  // String(input ?? '') — гарантируем, что работаем со строкой:
  // null/undefined превращаются в пустую строку (??  — оператор «нулевого слияния»).
  return String(input ?? '').replace(/[&<>"'/]/g, (ch) => {
    switch (ch) {
      case '&':  // & -> &   (обязательно ПЕРВЫМ, иначе новые & не заменятся)
        return '&' + 'amp;';
      case '<':  // < -> <
        return '&' + 'lt;';
      case '>':  // > -> >
        return '&' + 'gt;';
      case '"':  // " -> "
        return '&' + 'quot;';
      case "'":  // ' -> &#x27;
        return '&' + '#x27;';
      default:   // / -> &#x2F;  (закрытие тегов вида </script>)
        return '&' + '#x2F;';
    }
  });
}

/**
 * sanitizeText(input) — нормализация свободного текста.
 * Убирает управляющие символы (коды 0x00–0x1F, 0x7F — их нельзя вводить с
 * клавиатуры, в них нет смысла) и обрезает пробелы по краям (trim).
 * Это «черновое» приведение к нормальному виду перед валидацией/сохранением.
 */
function sanitizeText(input) {
  return String(input ?? '')
    .replace(/[\u0000-\u001F\u007F]/g, '') // удалить управляющие символы
    .trim();                               // убрать пробелы в начале и конце
}

/** isValidUsername: политика логина — 3–32 символа, только латиница/цифры/_. */
function isValidUsername(username) {
  return typeof username === 'string' && /^[a-zA-Z0-9_]{3,32}$/.test(username);
}

/** isValidPassword: политика пароля — 8–128 символов.
 *  ВАЖНО: пароль в БД хранится ТОЛЬКО как bcrypt-хэш, никогда в открытом виде. */
function isValidPassword(password) {
  return typeof password === 'string' && password.length >= 8 && password.length <= 128;
}

/** isValidTitle: заголовок поста — от 1 до 120 символов (защита от гигантских payload). */
function isValidTitle(title) {
  return typeof title === 'string' && title.length >= 1 && title.length <= 120;
}

/** isValidContent: текст поста — от 1 до 5000 символов. */
function isValidContent(content) {
  return typeof content === 'string' && content.length >= 1 && content.length <= 5000;
}

// Экспортируем все функции для использования в роутах и тестах.
module.exports = {
  escapeHtml,
  sanitizeText,
  isValidUsername,
  isValidPassword,
  isValidTitle,
  isValidContent,
};

