'use strict';

// =============================================================================
// ТОЧКА ВХОДА ПРИЛОЖЕНИЯ
// -----------------------------------------------------------------------------
// Этот файл — «главный» файл программы. Когда вы запускаете `npm start`,
// Node.js выполняет именно его (см. поле "main"/"start" в package.json).
// Задача файла: собрать все части приложения вместе и запустить сервер.
// =============================================================================

// Подключаем встроенные модули Node.js для работы с файловой системой.
// `node:` перед именем модуля — явное указание, что модуль встроенный.
const fs = require('node:fs');
const path = require('node:path');

// Подключаем наши собственные модули (относительные пути от этого файла):
const { getConfig } = require('./src/config'); // читает настройки из переменных окружения
const { createDb } = require('./src/db');      // создаёт базу данных SQLite
const { createApp } = require('./src/app');    // собирает Express-приложение

// Получаем конфигурацию: порт, путь к БД, JWT-секрет и т.д.
// getConfig() без аргументов читает process.env — переменные окружения процесса.
const config = getConfig();

// SQLite хранит данные в файле. Если путь отличается от ':memory:' (то есть
// это настоящий файл на диске), нужно заранее создать папку для него,
// иначе база не сможет открыться ("unable to open database file").
if (config.dbPath !== ':memory:') {
  // path.dirname() — берёт "папку" из пути; { recursive: true } — создаёт все
  // промежуточные папки и не падает, если папка уже существует.
  fs.mkdirSync(path.dirname(config.dbPath), { recursive: true });
}

// Создаём базу данных (схему таблиц + демо-данные) — подробности в src/db.js.
const db = createDb({ path: config.dbPath });

// Собираем Express-приложение, передавая ему базу данных и конфигурацию.
// Приложение хранит их в app.locals, поэтому роуты могут к ним обращаться.
const app = createApp({ db, config });

// Запускаем HTTP-сервер: слушаем порт config.port.
// Колбэк выполнится, когда сервер реально начал принимать соединения.
app.listen(config.port, () => {
  console.log(`[server] Secure API listening on http://localhost:${config.port}`);
  // Подсказка с демо-доступами (пароли в БД хранятся только как bcrypt-хэши).
  console.log('[server] Demo logins -> admin / Admin123!  |  alice / Alice123!');
});

// =============================================================================
// ЗАЧЕМ ТАК:
// - Разделение на config / db / app позволяет переиспользовать приложение в
//   тестах (тесты поднимают свой экземпляр с базой в памяти, см. test/).
// - Все секреты (JWT_SECRET) приходят из окружения, а не «зашиты» в код —
//   это правило безопасной разработки (нельзя коммитить секреты в репозиторий).
// =============================================================================